// Bundles the desktop SQLite migrations into the app (the phone cannot read files from backend/src).
// Reads every .sql file listed in the journal, in journal order, and writes src/core/generated/migrations.ts.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, "../../backend/src/infrastructure/orm/sqlite/migrations");
const journal = JSON.parse(readFileSync(path.join(dir, "meta", "_journal.json"), "utf8"));
if (journal.dialect !== "sqlite") throw new Error("journal is not a sqlite journal");

const entries = journal.entries.map((e) => ({
  idx: e.idx,
  tag: e.tag,
  sql: readFileSync(path.join(dir, `${e.tag}.sql`), "utf8"),
}));

const body = entries
  .map(
    (e) =>
      `  {\n    idx: ${e.idx},\n    tag: ${JSON.stringify(e.tag)},\n    sql: ${JSON.stringify(e.sql)},\n  },\n`,
  )
  .join("");

const fingerprint = JSON.parse(
  readFileSync(path.join(dir, "meta", "schema-fingerprint.json"), "utf8"),
);

const out =
  "// GENERATED by scripts/bundle-migrations.mjs — do not edit. Source: backend/src/infrastructure/orm/sqlite/migrations.\n" +
  "export const MIGRATIONS: { idx: number; tag: string; sql: string }[] = [\n" +
  body +
  "];\n\n" +
  `export const JOURNAL_LAST_IDX = ${entries.at(-1).idx};\n\n` +
  `export const COMMITTED_FINGERPRINT = ${JSON.stringify(fingerprint)} as unknown as import("../schemaFingerprint").SqliteFingerprint;\n`;

const target = path.resolve(here, "../src/core/generated/migrations.ts");
mkdirSync(path.dirname(target), { recursive: true });
writeFileSync(target, out);
// Same formatting as the committed file, so `prettier --check` stays green after a regeneration.
execFileSync("npx", ["--yes", "prettier", "--write", target], { stdio: "ignore" });
console.log(`wrote ${entries.length} migrations to ${path.relative(process.cwd(), target)}`);
