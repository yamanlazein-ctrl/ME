// Generates src/ui/tokens.generated.ts from the desktop's src/styles.css (the single source of the brand): the `:root`
// block is the desktop's default DARK theme, `.light` the soft light theme. oklch() values are converted to hex.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(join(here, "../../src/styles.css"), "utf8");

/** The body of the first `selector { … }` rule that defines --background (the file has several `:root` rules). */
function block(selector) {
  let from = 0;
  for (;;) {
    const start = css.indexOf(`\n${selector} {`, from);
    if (start < 0) throw new Error(`no ${selector} block with --background`);
    const open = css.indexOf("{", start);
    let depth = 0;
    let end = open;
    for (; end < css.length; end++) {
      if (css[end] === "{") depth++;
      if (css[end] === "}" && --depth === 0) break;
    }
    const body = css.slice(open + 1, end);
    if (body.includes("--background:")) return body;
    from = end;
  }
}

function oklchToHex(l, c, h) {
  const a = c * Math.cos((h * Math.PI) / 180);
  const b = c * Math.sin((h * Math.PI) / 180);
  const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const lin = [
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
  ];
  const enc = (v) => {
    const x = Math.min(1, Math.max(0, v));
    return x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
  };
  return `#${lin
    .map((v) =>
      Math.round(enc(v) * 255)
        .toString(16)
        .padStart(2, "0"),
    )
    .join("")}`;
}

function vars(body) {
  const out = {};
  for (const m of body.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)) {
    let v = m[2].trim();
    const ok = /^oklch\(([\d.]+)\s+([\d.]+)\s+([\d.]+)\)$/.exec(v);
    if (ok) v = oklchToHex(Number(ok[1]), Number(ok[2]), Number(ok[3]));
    if (/^#[0-9a-f]{6}$/i.test(v)) out[m[1]] = v.toLowerCase();
  }
  return out;
}

const camel = (k) => k.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const pick = (v) =>
  Object.fromEntries(
    Object.entries(v)
      .filter(([k]) => !k.startsWith("sidebar") && !k.startsWith("chart"))
      .map(([k, val]) => [camel(k), val]),
  );

const dark = pick(vars(block(":root")));
const light = pick({ ...vars(block(":root")), ...vars(block(".light")) });
const text = `// GENERATED by scripts/gen-tokens.mjs from the desktop's src/styles.css - do not edit by hand.\nexport const darkTokens = ${JSON.stringify(dark, null, 2)} as const;\n\nexport const lightTokens = ${JSON.stringify(light, null, 2)} as const;\n`;
writeFileSync(join(here, "../src/ui/tokens.generated.ts"), text);
console.log(`dark ${Object.keys(dark).length} tokens, light ${Object.keys(light).length} tokens`);
