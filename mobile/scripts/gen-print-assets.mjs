// Generates src/print/generated/desktopPrint.ts from the desktop's print stylesheet (src/components/print/print.css) and
// logo (src/assets/logo-motard-icon.png), so the phone's PDFs use the desktop's printed design byte for byte. A unit
// test (test/unit/print-desktop.test.ts) fails when the desktop files change and this was not re-run.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(join(here, "../../src/components/print/print.css"), "utf8");
const logo = readFileSync(join(here, "../../src/assets/logo-motard-icon.png")).toString("base64");

const out = `// GENERATED by scripts/gen-print-assets.mjs from the desktop's print.css and logo. Do not edit by hand.
export const DESKTOP_PRINT_CSS = ${JSON.stringify(css)};
export const DESKTOP_LOGO_DATA_URI = ${JSON.stringify(`data:image/png;base64,${logo}`)};
`;
writeFileSync(join(here, "../src/print/generated/desktopPrint.ts"), out);
console.log(`desktopPrint.ts: css ${css.length} chars, logo ${logo.length} base64 chars`);
