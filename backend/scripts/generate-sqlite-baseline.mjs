const q = (id) => `"${id}"`;
/** A v4 UUID from built-ins only (no app function needed); `random() & 3` cannot overflow. */
const UUID_DEFAULT =
  "(lower(hex(randomblob(4)) || '-' || hex(randomblob(2)) || '-4' || substr(hex(randomblob(2)), 2) || '-' || " +
  "substr('89ab', 1 + (random() & 3), 1) || substr(hex(randomblob(2)), 2) || '-' || hex(randomblob(6))))";
/** Wall-clock µs text from built-ins (ms precision, padded): DDL fallback only — the app always binds the tx clock. */
const WALL_NOW = "(strftime('%Y-%m-%dT%H:%M:%f', 'now') || '000Z')";
/** The writer stamps the transaction clock into motard_tx_state at BEGIN (connection layer, T042). */
const TX_NOW = `COALESCE((SELECT "ts" FROM "motard_tx_state" WHERE "id" = 1), ${WALL_NOW})`;
const txFlag = (name) => `COALESCE((SELECT "${name}" FROM "motard_tx_state" WHERE "id" = 1), 0)`;
const TS_GLOB = "[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]T[0-9][0-9]:[0-9][0-9]:[0-9][0-9].[0-9][0-9][0-9][0-9][0-9][0-9]Z";

/** Exact numeric literal → scaled integer text (round half away from zero; literals here are exact). */
function scaled(literal, scale) {
  const neg = literal.startsWith("-");
  const [i, f = ""] = literal.replace(/^[-+]/, "").split(".");
  const digits = (i + f.padEnd(scale, "0").slice(0, scale)).replace(/^0+(?=\d)/, "");
  if (f.length > scale && Number(f[scale]) >= 5) throw new Error(`default ${literal} needs rounding at scale ${scale}`);
  return (neg && digits !== "0" ? "-" : "") + digits;
}

/** jsonb key order (length, then bytes) — same rule as sqlite/types.ts toJsonbText. */
function jsonbText(value) {
  const norm = (v) => {
    if (Array.isArray(v)) return v.map(norm);
    if (v && typeof v === "object") {
      const out = {};
      for (const k of Object.keys(v).sort((a, b) => {
        const ba = Buffer.from(a), bb = Buffer.from(b);
        return ba.length !== bb.length ? ba.length - bb.length : Buffer.compare(ba, bb);
      })) out[k] = norm(v[k]);
      return out;
    }
    return v;
  };
  return JSON.stringify(norm(value));
}
const sqlString = (s) => `'${s.replace(/'/g, "''")}'`;

function defaultExpr(table, col) {
  const d = col.column_default;
  if (d === null) return null;
  if (d === "now()") return WALL_NOW;
  if (d === "gen_random_uuid()" || d === "uuid_generate_v4()") return UUID_DEFAULT;
  if (/^nextval\(/.test(d)) return null; // serial: AUTOINCREMENT PK, or app-supplied via motard_sequences
  if (d === "true") return "1";
  if (d === "false") return "0";
  if (/^-?\d+(\.\d+)?$/.test(d)) return col.data_type === "numeric" ? scaled(d, col.numeric_scale) : d;
  let m = /^'((?:[^']|'')*)'::(character varying|text)$/.exec(d);
  if (m) return sqlString(m[1].replace(/''/g, "'"));
  m = /^'((?:[^']|'')*)'::jsonb$/.exec(d);
  if (m) return sqlString(jsonbText(JSON.parse(m[1].replace(/''/g, "'"))));
  if (/^'\{\}'::(text|uuid)\[\]$/.test(d)) return "'[]'";
  throw new Error(`unmapped default ${table}.${col.column_name}: ${d}`);
}

function storage(col) {
  const t = col.data_type;
  if (t === "ARRAY" || ["uuid", "text", "character varying", "timestamp with time zone", "date", "jsonb", "inet"].includes(t)) return "TEXT";
  if (["integer", "bigint", "numeric", "boolean"].includes(t)) return "INTEGER";
  throw new Error(`unmapped type ${col.table_name}.${col.column_name}: ${t}`);
}

/** Type guards that PostgreSQL enforces through the column type itself. */
function typeChecks(table, col) {
  const c = q(col.column_name);
  const name = (kind) => `ck_sqlite_${kind}__${table}__${col.column_name}`;
  const nullOr = (e) => `${c} IS NULL OR (${e})`;
  switch (col.data_type) {
    case "character varying":
      return [[`ck_sqlite_len_${col.character_maximum_length}__${table}__${col.column_name}`, `length(${c}) <= ${col.character_maximum_length}`]];
    case "jsonb":
      return [[name("json"), nullOr(`json_valid(${c})`)]];
    case "ARRAY":
      return [[name("arr"), nullOr(`json_valid(${c}) AND json_type(${c}) = 'array'`)]];
    case "boolean":
      return [[name("bool"), `${c} IN (0, 1)`]];
    case "date":
      return [[name("date"), nullOr(`length(${c}) = 10 AND date(${c}) = ${c}`)]];
    case "timestamp with time zone":
      return [[name("ts"), nullOr(`${c} GLOB '${TS_GLOB}'`)]];
    default:
      return [];
  }
}

/** PG boolean expression (CHECK / partial-index WHERE) → SQLite. Fails on anything unrecognized. */
function translateExpr(expr, ctx) {
  let s = expr;
  // `= ANY ((ARRAY['a'::character varying, …])::text[])` → `IN ('a', …)`
  s = s.replace(/=\s*ANY\s*\(\(ARRAY\[([^\]]*)\]\)::[a-z ]+\[\]\)/g, (_, items) =>
    `IN (${items.split(",").map((x) => x.trim().replace(/::[a-z ]+$/, "")).join(", ")})`);
  s = s.replace(/'((?:[^']|'')*)'::(character varying|text)/g, "'$1'");
  s = s.replace(/\(([a-z_][a-z0-9_]*)\)::(text|character varying|double precision|numeric)/g, "$1");
  s = s.replace(/\((-?\d+(?:\.\d+)?)\)::(numeric|double precision|integer)/g, "$1");
  s = s.replace(/\b(\w+) = true\b/g, "$1 = 1").replace(/\b(\w+) = false\b/g, "$1 = 0");
  if (/::|ARRAY\[|ANY\s*\(|~~|ILIKE|now\(\)/i.test(s)) throw new Error(`untranslated expression in ${ctx}: ${s}`);
  return s;
}

/**
 * `cashbox_daily_apply_delta(tenant, currency, date, delta)` inlined as two statements
 * (research-appendix-pg-triggers.sql): seed/upsert the day from the previous day's closing
 * balance (or the session opening balance), then shift every later day. `guard` must be
 * true for the call to happen (the plpgsql IF branches); NULL counts as false.
 */
function applyDelta({ tenant, currency, date, delta, guard }) {
  const when = `(${guard}) AND (${delta}) IS NOT NULL AND (${delta}) <> 0`;
  return `  INSERT INTO "cashbox_daily_balances" ("tenant_id", "currency", "balance_date", "closing_balance", "updated_at")
  SELECT ${tenant}, ${currency}, ${date},
         COALESCE(
           (SELECT c."closing_balance" FROM "cashbox_daily_balances" c
             WHERE c."tenant_id" = ${tenant} AND c."currency" = ${currency} AND c."balance_date" < ${date}
             ORDER BY c."balance_date" DESC LIMIT 1),
           (SELECT COALESCE(s."opening_balance", 0) FROM "cashbox_sessions" s
             WHERE s."tenant_id" = ${tenant} AND s."currency" = ${currency} LIMIT 1),
           0) + (${delta}),
         ${TX_NOW}
   WHERE ${when}
  ON CONFLICT ("tenant_id", "currency", "balance_date") DO UPDATE SET
    "closing_balance" = "closing_balance" + (${delta}),
    "updated_at" = ${TX_NOW};
  UPDATE "cashbox_daily_balances"
     SET "closing_balance" = "closing_balance" + (${delta}), "updated_at" = ${TX_NOW}
   WHERE ${when}
     AND "tenant_id" = ${tenant} AND "currency" = ${currency} AND "balance_date" > ${date};`;
}

/** T1–T7 (data-model.md §4) transcribed from the verbatim PG bodies (research-appendix-pg-triggers.sql). */
function triggersSql() {
  const amt = (r) => `(COALESCE(${r}."debit", 0) + COALESCE(${r}."credit", 0))`;
  const remapOk = `${txFlag("allow_party_remap")} = 1
       AND NEW."debit" = OLD."debit" AND NEW."credit" = OLD."credit" AND NEW."currency" = OLD."currency"
       AND NEW."date" = OLD."date" AND NEW."type" = OLD."type" AND NEW."status" = OLD."status"
       AND NEW."reference_id" IS OLD."reference_id" AND NEW."reference_type" IS OLD."reference_type"`;
  const finChanged = `NEW."debit" <> OLD."debit" OR NEW."credit" <> OLD."credit"
       OR NEW."currency" <> OLD."currency" OR NEW."party_id" <> OLD."party_id"
       OR NEW."date" <> OLD."date" OR NEW."type" <> OLD."type"
       OR NEW."reference_id" IS NOT OLD."reference_id"
       OR NEW."reference_type" IS NOT OLD."reference_type"`;
  const bothNotCash = `OLD."cash_impact" NOT IN ('in', 'out') AND NEW."cash_impact" NOT IN ('in', 'out')`;
  const stampApplied = `  INSERT INTO "motard_sequences" ("name", "value") VALUES ('sync_inbox_applied_seq', 1)
    ON CONFLICT ("name") DO UPDATE SET "value" = "value" + 1;
  UPDATE "sync_inbox"
     SET "applied_seq" = (SELECT "value" FROM "motard_sequences" WHERE "name" = 'sync_inbox_applied_seq'),
         "applied_at" = COALESCE("applied_at", ${WALL_NOW})
   WHERE "id" = NEW."id";`;
  const manualIn = (r) => `CASE WHEN ${r}."direction" = 'in' THEN ${r}."amount" ELSE -${r}."amount" END`;
  const manualOut = (r) => `CASE WHEN ${r}."direction" = 'in' THEN -${r}."amount" ELSE ${r}."amount" END`;
  return `-- ── Trigger equivalents T1–T7 (data-model.md §4, T037) ──
-- Session flags and the transaction clock come from the single row of motard_tx_state, which the
-- writer stamps at BEGIN and resets before COMMIT (T042). The schema calls no app functions, so it
-- works under trusted_schema=OFF; a missing row means flags 0 (fail closed).

-- T1 trg_ledger_entries_append_only (PG: BEFORE DELETE OR UPDATE, fn_ledger_entries_append_only).
-- allow_dye_purge permits DELETE only (research I-7); UPDATE stays guarded.
CREATE TRIGGER "trg_ledger_entries_append_only_bd" BEFORE DELETE ON "ledger_entries"
WHEN ${txFlag("allow_dye_purge")} = 0
BEGIN
  SELECT RAISE(ABORT, 'ledger_entries is append-only: DELETE not allowed');
END;

CREATE TRIGGER "trg_ledger_entries_append_only_bu" BEFORE UPDATE ON "ledger_entries"
WHEN NOT COALESCE((${remapOk}), 0)
BEGIN
  SELECT RAISE(ABORT, 'ledger_entries: cannot modify already-cancelled rows') WHERE OLD."status" = 'cancelled';
  SELECT RAISE(ABORT, 'ledger_entries: UPDATE only allowed for cancellation (status→cancelled)') WHERE NEW."status" <> 'cancelled';
  SELECT RAISE(ABORT, 'ledger_entries: financial columns are immutable') WHERE ${finChanged};
END;

-- T2 cashbox_daily_ledger_ai (AFTER INSERT ON ledger_entries).
CREATE TRIGGER "cashbox_daily_ledger_ai" AFTER INSERT ON "ledger_entries"
WHEN COALESCE(NEW."status", 'active') = 'active' AND NEW."cash_impact" IN ('in', 'out')
BEGIN
${applyDelta({
  tenant: 'NEW."tenant_id"', currency: 'NEW."currency"', date: 'NEW."date"',
  delta: `CASE WHEN NEW."cash_impact" = 'in' THEN ${amt("NEW")} ELSE -${amt("NEW")} END`, guard: "1",
})}
END;

-- T3 cashbox_daily_ledger_au (AFTER UPDATE OF status, cash_impact, debit, credit): reverse on
-- active→cancelled, re-apply on cancelled→active.
CREATE TRIGGER "cashbox_daily_ledger_au" AFTER UPDATE OF "status", "cash_impact", "debit", "credit" ON "ledger_entries"
WHEN NOT COALESCE((${bothNotCash}), 0)
BEGIN
${applyDelta({
  tenant: 'OLD."tenant_id"', currency: 'OLD."currency"', date: 'OLD."date"',
  delta: `CASE WHEN OLD."cash_impact" = 'in' THEN -${amt("OLD")} ELSE ${amt("OLD")} END`,
  guard: `COALESCE(OLD."status", 'active') = 'active' AND COALESCE(NEW."status", 'active') = 'cancelled' AND OLD."cash_impact" IN ('in', 'out')`,
})}
${applyDelta({
  tenant: 'NEW."tenant_id"', currency: 'NEW."currency"', date: 'NEW."date"',
  delta: `CASE WHEN NEW."cash_impact" = 'in' THEN ${amt("NEW")} ELSE -${amt("NEW")} END`,
  guard: `COALESCE(OLD."status", 'active') = 'cancelled' AND COALESCE(NEW."status", 'active') = 'active' AND NEW."cash_impact" IN ('in', 'out')`,
})}
END;

-- T4 cashbox_daily_manual_aiud (AFTER INSERT OR DELETE OR UPDATE ON manual_movements).
CREATE TRIGGER "cashbox_daily_manual_aiud_ai" AFTER INSERT ON "manual_movements"
BEGIN
${applyDelta({ tenant: 'NEW."tenant_id"', currency: 'NEW."currency"', date: 'NEW."date"', delta: manualIn("NEW"), guard: "1" })}
END;

CREATE TRIGGER "cashbox_daily_manual_aiud_ad" AFTER DELETE ON "manual_movements"
BEGIN
${applyDelta({ tenant: 'OLD."tenant_id"', currency: 'OLD."currency"', date: 'OLD."date"', delta: manualOut("OLD"), guard: "1" })}
END;

CREATE TRIGGER "cashbox_daily_manual_aiud_au" AFTER UPDATE ON "manual_movements"
BEGIN
${applyDelta({ tenant: 'OLD."tenant_id"', currency: 'OLD."currency"', date: 'OLD."date"', delta: manualOut("OLD"), guard: "1" })}
${applyDelta({ tenant: 'NEW."tenant_id"', currency: 'NEW."currency"', date: 'NEW."date"', delta: manualIn("NEW"), guard: "1" })}
END;

-- T5/T6 license audit events are append-only.
CREATE TRIGGER "trg_license_audit_events_no_update" BEFORE UPDATE ON "license_audit_events"
BEGIN
  SELECT RAISE(ABORT, 'license_audit_events is append-only (operation UPDATE)');
END;

CREATE TRIGGER "trg_license_audit_events_no_delete" BEFORE DELETE ON "license_audit_events"
BEGIN
  SELECT RAISE(ABORT, 'license_audit_events is append-only (operation DELETE)');
END;

-- T7 trg_sync_inbox_applied_seq (PG: BEFORE INSERT OR UPDATE OF status). SQLite cannot assign
-- NEW in a BEFORE trigger, so the stamp is an AFTER trigger updating the row. The PG advisory
-- lock is unnecessary: the single writer already serializes commits.
CREATE TRIGGER "trg_sync_inbox_applied_seq_ai" AFTER INSERT ON "sync_inbox"
WHEN NEW."status" = 'applied'
BEGIN
${stampApplied}
END;

CREATE TRIGGER "trg_sync_inbox_applied_seq_au" AFTER UPDATE OF "status" ON "sync_inbox"
WHEN NEW."status" = 'applied' AND OLD."status" IS NOT 'applied'
BEGIN
${stampApplied}
END;
`;
}

const client = new pg.Client({ connectionString: URL });
await client.connect();
const { rows: jr } = await client.query(
  "SELECT count(*)::int AS n FROM information_schema.tables WHERE table_schema = 'public' AND table_type = 'BASE TABLE'",
);
const { rows: columns } = await client.query(
  `SELECT table_name, column_name, ordinal_position, is_nullable, column_default, data_type,
          character_maximum_length, numeric_precision, numeric_scale
     FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name IN (SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' AND table_type = 'BASE TABLE')
    ORDER BY table_name, ordinal_position`,
);
const { rows: constraints } = await client.query(
  `SELECT c.conrelid::regclass::text AS table_name, c.conname, c.contype, pg_get_constraintdef(c.oid) AS def,
          ARRAY(SELECT a.attname FROM unnest(c.conkey) WITH ORDINALITY k(n, i) JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.n ORDER BY k.i)::text[] AS cols,
          c.confrelid::regclass::text AS ref_table,
          ARRAY(SELECT a.attname FROM unnest(c.confkey) WITH ORDINALITY k(n, i) JOIN pg_attribute a ON a.attrelid = c.confrelid AND a.attnum = k.n ORDER BY k.i)::text[] AS ref_cols,
          c.confdeltype
     FROM pg_constraint c
    WHERE c.connamespace = 'public'::regnamespace AND c.contype IN ('p','u','c','f')
    ORDER BY c.conrelid::regclass::text, c.contype, c.conname`,
);
const { rows: indexes } = await client.query(
  `SELECT tablename, indexname, indexdef FROM pg_indexes
    WHERE schemaname = 'public'
      AND indexname NOT IN (SELECT conname FROM pg_constraint WHERE contype IN ('p','u') AND connamespace = 'public'::regnamespace)
    ORDER BY tablename, indexname`,
);
await client.end();

const byTable = new Map();
for (const c of columns) byTable.set(c.table_name, [...(byTable.get(c.table_name) ?? []), c]);
if (byTable.size !== jr[0].n) throw new Error("column/table count mismatch");
if (byTable.has("party_balances")) throw new Error("party_balances must not exist (dropped by migration 0038)");

const out = [];
out.push(
  "-- GENERATED by scripts/generate-sqlite-baseline.mjs from the live PostgreSQL schema",
  "-- (specs/001-desktop-sqlite-engine T036/T037). Do not edit by hand; regenerate instead.",
  "-- Self-contained: no app-defined functions (trusted_schema=OFF). Transaction clock and session",
  "-- flags live in motard_tx_state, stamped by the connection layer's writer at BEGIN.",
  "",
);
const counts = { tables: 0, p: 0, u: 0, c: 0, f: 0, idx: 0, ginSkipped: 0 };

for (const [table, cols] of [...byTable].sort(([a], [b]) => a.localeCompare(b))) {
  counts.tables++;
  const cons = constraints.filter((c) => c.table_name === table);
  const pk = cons.find((c) => c.contype === "p");
  const serialPk = pk && pk.cols.length === 1 && /^nextval\(/.test(cols.find((c) => c.column_name === pk.cols[0]).column_default ?? "");
  const lines = [];
  for (const col of cols) {
    let line = `  ${q(col.column_name)} ${storage(col)}`;
    if (serialPk && col.column_name === pk.cols[0]) {
      line += ` CONSTRAINT ${q(pk.conname)} PRIMARY KEY AUTOINCREMENT`;
    } else {
      if (col.is_nullable === "NO") line += " NOT NULL";
      const d = defaultExpr(table, col);
      if (d !== null) line += ` DEFAULT ${d}`;
    }
    lines.push(line);
  }
  for (const c of cons) {
    if (c.contype === "p") {
      counts.p++;
      if (!serialPk) lines.push(`  CONSTRAINT ${q(c.conname)} PRIMARY KEY (${c.cols.map(q).join(", ")})`);
    } else if (c.contype === "u") {
      counts.u++;
      lines.push(`  CONSTRAINT ${q(c.conname)} UNIQUE (${c.cols.map(q).join(", ")})`);
    } else if (c.contype === "c") {
      counts.c++;
      const m = /^CHECK \((.*)\)$/s.exec(c.def);
      if (!m) throw new Error(`unexpected CHECK ${c.conname}: ${c.def}`);
      lines.push(`  CONSTRAINT ${q(c.conname)} CHECK (${translateExpr(m[1], c.conname)})`);
    } else if (c.contype === "f") {
      counts.f++;
      const action = { a: "", r: " ON DELETE RESTRICT", c: " ON DELETE CASCADE", n: " ON DELETE SET NULL", d: " ON DELETE SET DEFAULT" }[c.confdeltype];
      if (action === undefined) throw new Error(`unexpected FK action ${c.confdeltype} on ${c.conname}`);
      lines.push(
        `  CONSTRAINT ${q(c.conname)} FOREIGN KEY (${c.cols.map(q).join(", ")}) REFERENCES ${q(c.ref_table)} (${c.ref_cols.map(q).join(", ")})${action}`,
      );
    }
  }
  for (const col of cols) for (const [name, expr] of typeChecks(table, col)) lines.push(`  CONSTRAINT ${q(name)} CHECK (${expr})`);
  out.push(`CREATE TABLE ${q(table)} (\n${lines.join(",\n")}\n) STRICT;`, "");
}

for (const ix of indexes) {
  const m = /^CREATE (UNIQUE )?INDEX (\S+) ON public\.(\S+) USING (\w+) \((.*?)\)(?: WHERE \((.*)\))?$/s.exec(ix.indexdef);
  if (!m) throw new Error(`unparsed index ${ix.indexname}: ${ix.indexdef}`);
  const [, unique, name, table, method, colList, where] = m;
  if (method === "gin") {
    counts.ginSkipped++;
    continue; // trigram search indexes: no SQLite equivalent (research R7)
  }
  if (method !== "btree") throw new Error(`unexpected index method ${method} on ${name}`);
  const items = colList.split(",").map((s) => {
    const [col, ...rest] = s.trim().split(/\s+/);
    if (!/^[a-z_][a-z0-9_]*$/.test(col) || rest.some((r) => !["DESC", "ASC"].includes(r))) throw new Error(`unexpected index item ${s} in ${name}`);
    return [q(col), ...rest].join(" ");
  });
  counts.idx++;
  out.push(
    `CREATE ${unique ?? ""}INDEX ${q(name)} ON ${q(table)} (${items.join(", ")})${where ? ` WHERE ${translateExpr(where, name)}` : ""};`,
  );
}
out.push("");

