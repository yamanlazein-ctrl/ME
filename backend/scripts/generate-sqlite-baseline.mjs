#!/usr/bin/env node
/**
 * Generate the desktop SQLite baseline DDL from the live PostgreSQL schema
 * (specs/001-desktop-sqlite-engine T036; data-model.md §1–§2, research R5–R7).
 *
 *   node scripts/generate-sqlite-baseline.mjs --url postgresql://… [--check]
 *
 * Reads the migrated PG catalog directly (pg_get_constraintdef / pg_get_indexdef — never the
 * lower-cased fingerprint text, research R13c) and writes
 * src/infrastructure/orm/sqlite/migrations/0000_baseline.sql:
 *   - every live table (53) as a STRICT table, columns in ordinal order;
 *   - every PK / UNIQUE / CHECK / FK under its PG constraint name (CHECK `= ANY(ARRAY[…])` → `IN (…)`),
 *     FKs with identical columns and ON DELETE action — the 24 non-enforced tenant references stay absent;
 *   - every btree index with its partial WHERE; GIN/trigram indexes are omitted (R7);
 *   - type-guard CHECKs named `ck_sqlite_<kind>[_<n>]__<table>__<column>` (length, json, boolean, date,
 *     timestamp, array) so the error mapping (T047) can reproduce PG's message;
 *   - the SQLite-only runtime tables motard_meta, motard_sequences and motard_tx_state (transaction
 *     clock + session flags, read by the triggers; the schema calls no app-defined functions).
 * Trigger equivalents T1–T7 (T037) are generated by triggersSql() below.
 * `--check` fails if the committed file differs from a fresh generation.
 */
